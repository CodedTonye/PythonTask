#ALGORITHM FOR MAKING A CUP OF TEA:

#Step 1: Get the resources needed (kettle, cup, tea bag, water, milk and sugar, if necessary)

#Step 2: Fill the kettle with water

#Step 3: Boil the water on gas or electric burner. If the water is hot enough, take it down, else wait for the water to get hot (Loop).

#Step 4: Place the Tea bag in the cup and pour the boiling water into the cup, wait for 2 to 3 minutes then remove and dispose the tea bag.

#Step 5: If sugar is needed, then add one teaspoon of sugar and stir the tea, else, do not add sugar (if/else).

#Step 6: Serve the hot tea.
