#ATM Withdrawal Algorithm

#Step 1: Approach the machine

#Step 2: Insert the ATM Card into the card reader

#Step 3: Enter 4-digit PIN

#Step 4: The system checks to validate the PIN, if incorrect, prompts re-entry 3 times max.

#Step 5: Select withdrawal under transaction type

#Step 6: Select account type: Savings or Credit

#Step 7: Enter withdrawal amount

#Step 8: System checks to verify account balance (If there is no funds up to the withdrawal limit, the machine will display "Insufficient funds")

#Step 9: ATM dispenses requested money and updates the account balance by sending a debit alert

#Step 10: Press cancel to eject your card and end transaction.
